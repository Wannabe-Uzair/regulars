// Builds the generated parts of the Tenure design code from tokens.json and the fonts:
//   brand/tokens.vars.css   CSS variables (never edit by hand)
//   brand/wordmark.js       the outlined TENURE word and descriptor (font-independent logo geometry)
//   brand/assets/*.svg      static logo lockups and device samples for tools that can't run kit.js
// usage: node tools/make-assets.mjs
import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'
const require = createRequire(import.meta.url)
const opentype = require('opentype.js')

const here = path.dirname(new URL(import.meta.url).pathname)
const brand = path.join(here, '..', 'brand')
const tokens = JSON.parse(fs.readFileSync(path.join(brand, 'tokens.json'), 'utf8'))
fs.mkdirSync(path.join(brand, 'assets'), { recursive: true })

/* ---------- 1. tokens.vars.css ---------- */
const kebab = (s) => s.replace(/([a-z])([0-9])/g, '$1-$2').replace(/_/g, '-')
let css = `/* GENERATED from tokens.json by tools/make-assets.mjs. Do not edit. */\n:root {\n`
// colour vars use the token names as they are (--rubber2); the hyphenated form (--rubber-2) is kept as an alias
for (const [k, v] of Object.entries(tokens.color)) { css += `  --${k}: ${v.hex};\n`; if (kebab(k) !== k) css += `  --${kebab(k)}: ${v.hex};\n` }
css += `  --display-line-height: ${tokens.type.display_line_height};\n`
css += `  --display-tracking: ${tokens.type.display_tracking_em}em;\n`
css += `  --label-tracking: ${tokens.font.label.tracking_em}em;\n`
css += `  --body-line-height: ${tokens.type.body_line_height};\n`
for (const [k, v] of Object.entries(tokens.type.screen_px_at_1920x1080)) css += `  --screen-${k}: ${v}px;\n`
for (const [k, v] of Object.entries(tokens.type.brochure_pt)) css += `  --brochure-${kebab(k)}: ${v}pt;\n`
for (const [k, v] of Object.entries(tokens.type.standee_pt)) if (typeof v === 'number') css += `  --standee-${k}: ${v}pt;\n`
css += `}\n`
fs.writeFileSync(path.join(brand, 'tokens.vars.css'), css)

/* ---------- 2. wordmark.js (outlined) ---------- */
function moved(p, dx, dy) {
  const q = new opentype.Path()
  for (const c of p.commands) {
    const n = { ...c }
    for (const k of ['x', 'x1', 'x2']) if (k in n) n[k] += dx
    for (const k of ['y', 'y1', 'y2']) if (k in n) n[k] += dy
    q.commands.push(n)
  }
  return q
}
const anton = opentype.loadSync(path.join(brand, 'fonts/Anton-Regular.ttf'))
const bcb = opentype.loadSync(path.join(brand, 'fonts/BarlowCondensed-Bold.ttf'))
const WORD = 'TENURE', DESC = 'MEMBER RETENTION FOR INDEPENDENT GYMS'

const wp = anton.getPath(WORD, 0, 0, 1000, { letterSpacing: 0.02 })
const wb = wp.getBoundingBox()
const capW = (anton.tables.os2.sCapHeight / anton.unitsPerEm) * 1000
const word = moved(wp, -wb.x1, capW)                    // cap top at y = 0, baseline at y = cap height
const W = wb.x2 - wb.x1

const dp0 = bcb.getPath(DESC, 0, 0, 1000, { letterSpacing: 0.14 })
const db0 = dp0.getBoundingBox()
const size = (1000 * W) / (db0.x2 - db0.x1)             // fit the descriptor to the word's width
const dp = bcb.getPath(DESC, 0, 0, size, { letterSpacing: 0.14 })
const db = dp.getBoundingBox()
const capD = (bcb.tables.os2.sCapHeight / bcb.unitsPerEm) * size
const desc = moved(dp, -db.x1, capD)

const WM = {
  word: { d: word.toPathData(2), w: +W.toFixed(2), h: +capW.toFixed(2), text: WORD, font: 'Anton 400, +0.02 em' },
  desc: { d: desc.toPathData(2), w: +(db.x2 - db.x1).toFixed(2), h: +capD.toFixed(2), size: +size.toFixed(2), text: DESC, font: 'Barlow Condensed 700, +0.14 em' },
}
fs.writeFileSync(path.join(brand, 'wordmark.js'),
  `/* GENERATED by tools/make-assets.mjs: the outlined Tenure wordmark and descriptor. Units: the word at 1000 units, cap top at y = 0. */\n` +
  `(function (root) { const WM = ${JSON.stringify(WM)};\n` +
  `  if (typeof module === 'object' && module.exports) module.exports = WM; else root.TENURE_WORDMARK = WM })(typeof self !== 'undefined' ? self : this)\n`)

/* ---------- 3. static assets ---------- */
delete require.cache[require.resolve(path.join(brand, 'wordmark.js'))]
const T = require(path.join(brand, 'kit.js'))
const out = (name, s) => fs.writeFileSync(path.join(brand, 'assets', name), s)
out('logo-chalk.svg', T.logo({ w: 1000 }))                                                    // on rubber
out('logo-rubber.svg', T.logo({ w: 1000, word: T.C.rubber, tapeColor: T.C.rubber }))          // on yellow
out('lockup-chalk.svg', T.logo({ w: 1000, descriptor: true }))
out('lockup-rubber.svg', T.logo({ w: 1000, word: T.C.rubber, tapeColor: T.C.rubber, descriptor: true, descColor: T.C.rubber }))
out('tape-3.svg', T.tape({ w: 1000, h: 60 }))
out('hazard-band.svg', T.hazard({ w: 1920, h: 36, stripe: 18 }))

// rubber-floor speckle: a seamless 512 px tile of EPDM-like flecks, used at low strength on rubber grounds only
let seed = 90; const rnd = () => ((seed = (seed * 1664525 + 1013904223) >>> 0) / 4294967296)
let dots = ''
const S = 512
for (let i = 0; i < 900; i++) {
  const x = rnd() * S, y = rnd() * S, r = 0.5 + rnd() * rnd() * 1.4
  const t = rnd(), col = t < 0.58 ? T.C.chalk : t < 0.88 ? T.C.steel : T.C.yellow
  const o = (0.08 + rnd() * 0.22).toFixed(2)
  for (const dx of [0, x < 3 ? S : x > S - 3 ? -S : null]) for (const dy of [0, y < 3 ? S : y > S - 3 ? -S : null]) {
    if (dx === null || dy === null) continue
    dots += `<circle cx="${(x + dx).toFixed(1)}" cy="${(y + dy).toFixed(1)}" r="${r.toFixed(2)}" fill="${col}" fill-opacity="${o}"/>`
  }
}
out('speckle-tile.svg', `<svg xmlns="http://www.w3.org/2000/svg" width="${S}" height="${S}" viewBox="0 0 ${S} ${S}">${dots}</svg>`)

console.log('word', WM.word.w, 'x', WM.word.h, '| descriptor size', WM.desc.size, 'cap', WM.desc.h)
console.log('wrote tokens.vars.css, wordmark.js, assets/', fs.readdirSync(path.join(brand, 'assets')).join(', '))
