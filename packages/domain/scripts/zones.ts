// Prints src/zones.data.ts from this Node's ICU. Run it from the repo root after a Node update:
//   node packages/domain/scripts/zones.ts > packages/domain/src/zones.data.ts
// It prints rather than writes because the domain lint bans fs and process (ARCHITECTURE §4).
// Why committed data: Firefox lacks Intl.Locale#getTimeZones, and browsers name some zones differently, while sign-up,
// Settings and the seed must agree.
import { getCountries } from 'libphonenumber-js/min'

/**
 * Current IANA names that ICU (so Node and Chrome) knows under an older name. Checked against tzdata's zone.tab when
 * written: these are all 19. Each must still resolve to a different name, or the script stops.
 */
const IANA_NAMES = [
  'Africa/Asmara',
  'America/Argentina/Buenos_Aires',
  'America/Argentina/Catamarca',
  'America/Argentina/Cordoba',
  'America/Argentina/Jujuy',
  'America/Argentina/Mendoza',
  'America/Atikokan',
  'America/Indiana/Indianapolis',
  'America/Kentucky/Louisville',
  'America/Nuuk',
  'Asia/Ho_Chi_Minh',
  'Asia/Kathmandu',
  'Asia/Kolkata',
  'Asia/Yangon',
  'Atlantic/Faroe',
  'Europe/Kyiv',
  'Pacific/Chuuk',
  'Pacific/Kanton',
  'Pacific/Pohnpei',
]

/** Two fixed instants, one in each half of the year, so a zone's standard offset is the smaller of the two. */
const INSTANTS = [new Date(Date.UTC(2026, 0, 15)), new Date(Date.UTC(2026, 6, 15))]

/** Minutes east of UTC at `at`, from Intl's "GMT+05:30" (or plain "GMT"). */
function offsetAt(timeZone: string, at: Date): number {
  const name = new Intl.DateTimeFormat('en-US', { timeZone, timeZoneName: 'longOffset' })
    .formatToParts(at)
    .find((p) => p.type === 'timeZoneName')?.value
  const m = /^GMT(?:([+-])(\d{2}):(\d{2}))?$/.exec(name ?? '')
  if (!m) throw new Error(`Unexpected offset "${name}" for ${timeZone}`)
  return m[1] ? (m[1] === '-' ? -1 : 1) * (Number(m[2]) * 60 + Number(m[3])) : 0
}

const standardOffset = (zone: string) => Math.min(...INSTANTS.map((at) => offsetAt(zone, at)))
const city = (zone: string) => zone.slice(zone.lastIndexOf('/') + 1).replaceAll('_', ' ')

/** East to west: the larger standard offset first, then by city name. */
const eastToWest = (a: string, b: string) =>
  standardOffset(b) - standardOffset(a) || city(a).localeCompare(city(b), 'en')

const zones: [string, string[]][] = []
const twelveHour: string[] = []
for (const country of getCountries()) {
  const list = new Intl.Locale(`und-${country}`).getTimeZones?.() ?? []
  if (list.length) zones.push([country, [...list].sort(eastToWest)])
  const cycle = new Intl.Locale(`und-${country}`).maximize().getHourCycles?.()[0]
  if (cycle === 'h11' || cycle === 'h12') twelveHour.push(country)
}

const known = new Set(zones.flatMap(([, list]) => list))
const aliases = IANA_NAMES.map((name) => {
  const icu = new Intl.DateTimeFormat('en-US', { timeZone: name }).resolvedOptions().timeZone
  if (icu === name || !known.has(icu)) throw new Error(`${name} is no longer an alias of a listed zone (${icu})`)
  return [name, icu] as const
})

const q = (s: string) => `'${s}'`

/** An array literal laid out as Prettier would (printWidth 120): on one line if it fits, else one item a line. */
function array(head: string, items: string[], tail: string, indent: string): string[] {
  const line = `${indent}${head}[${items.map(q).join(', ')}]${tail}`
  if (line.length <= 120) return [line]
  return [`${indent}${head}[`, ...items.map((s) => `${indent}  ${q(s)},`), `${indent}]${tail}`]
}

const out = [
  '// Generated by packages/domain/scripts/zones.ts from Node’s ICU. Do not edit: rerun the script (see its header).',
  '',
  '/** Each country’s time zones under ICU’s names, east to west (standard offset, then city). */',
  'export const ZONES: Readonly<Record<string, readonly string[]>> = {',
  ...zones.flatMap(([country, list]) => array(`${country}: `, list, ',', '  ')),
  '}',
  '',
  '/** Current IANA names (Firefox, maybe Safari) for zones ICU lists under an older name. */',
  'export const ZONE_ALIASES: Readonly<Record<string, string>> = {',
  ...aliases.map(([iana, icu]) => `  ${q(iana)}: ${q(icu)},`),
  '}',
  '',
  '/** Countries whose main language keeps a 12-hour clock (CLDR); every other country keeps a 24-hour one. */',
  ...array('export const TWELVE_HOUR_COUNTRIES: readonly string[] = ', twelveHour, '', ''),
]
console.log(out.join('\n'))
